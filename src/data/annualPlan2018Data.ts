export function getQuarterForMonth(month: string): '1ኛ' | '2ኛ' | '3ኛ' | '4ኛ' {
  if (['መስከረም', 'ጥቅምት', 'ኅዳር'].includes(month)) return '1ኛ';
  if (['ታኅሣሥ', 'ጥር', 'የካቲት'].includes(month)) return '2ኛ';
  if (['መጋቢት', 'ሚያዝያ', 'ግንቦት'].includes(month)) return '3ኛ';
  return '4ኛ'; // ሰኔ፣ ሐምሌ፣ ነሐሴ፣ ጳጉሜን
}
